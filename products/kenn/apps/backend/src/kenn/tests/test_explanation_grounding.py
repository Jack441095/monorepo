def test_explain_grade_structure_and_pedagogical_prose():
    """Verify explain_grade returns grounded pedagogical prose for the overall grade."""
    fake = FakeLiveBackend()
    snapshot = fake.query_session_state()

    meters = {
        "rms_dbfs": -16.0,
        "integrated_lufs": -13.0,
        "true_peak_dbtp": -0.5,  # -0.5 dBTP exceeds -1.0 dBTP
        "phase_correlation": 0.80,
        "crest_factor_db": 9.5,
        "spectral_energy": {
            "sub_20_60hz": 0.30,
            "low_mid_200_500hz": 0.32,
            "high_mid_2_6khz": 0.22,
            "air_10_20khz": 0.16,
        },
    }
    grade = _grade_for_meters(meters, snapshot)
    explanation = explain_grade(grade, meters=meters)

    assert explanation["ok"] is True
    assert explanation["grade_points"] == grade["points"]
    assert explanation["points_available"] == grade["points_available"]

    prose = explanation["teaching_prose"]
    assert f"{grade['points']:.1f} of {grade['points_available']:.0f} points" in prose
    assert "true peak reached -0.50 dBTP" in prose
    assert "Auditory guidance:" in prose

    # Cites relevant standards
    cites = explanation["cited_standards"]
    assert any("Spotify" in s for s in cites)
    assert any("AES TD1008" in s for s in cites)


def test_explain_grade_handles_ungraded_components_without_hallucination():
    """Verify explain_grade cleanly handles unmeasured/ungraded components."""
    # Combine grade without reference match (reference_match=None)
    partial_grade = combine_grade(
        technical={"mqm_score": 24.0, "points_available": 30.0, "meaning": "24 of 30", "unscored": []},
        declared_target={"points": 25.0, "points_available": 30.0, "note": "target note"},
        reference_match=None,
    )
    explanation = explain_grade(partial_grade, meters={})

    assert explanation["ok"] is True
    assert "reference match (no reference track supplied)" in explanation["teaching_prose"]
    assert len(explanation["ungraded"]) == 1
    assert explanation["ungraded"][0]["part"] == "reference_match"


