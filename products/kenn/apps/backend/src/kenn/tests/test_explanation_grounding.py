def test_explanation_measurements_are_strictly_grounded():
    """Extract every measurement from pedagogical explanations and assert strict grounding."""
    fake = FakeLiveBackend()
    snapshot = fake.query_session_state()

    # Known measured values
    measured_tp = 0.35
    measured_corr = -0.12
    measured_plr = 5.2
    measured_low_mid = 0.44
    measured_sub = 0.48
    measured_air = 0.07

    meters = {
        "rms_dbfs": -15.0,
        "integrated_lufs": -13.5,
        "true_peak_dbtp": measured_tp,
        "phase_correlation": measured_corr,
        "crest_factor_db": measured_plr,
        "spectral_energy": {
            "sub_20_60hz": measured_sub,
            "low_mid_200_500hz": measured_low_mid,
            "high_mid_2_6khz": 0.20,
            "air_10_20khz": measured_air,
        },
    }
    grade = _grade_for_meters(meters, snapshot)
    levers = generate_suggestion_levers(grade, snapshot, meters=meters)

    # Permitted set: standard constants + exact input meters
    allowed = set(_ALLOWED_STANDARD_MEASUREMENTS)
    allowed.update({
        f"{measured_tp:+.2f}dbtp".lower(),
        f"{measured_tp:.2f}dbtp".lower(),
        f"{measured_tp - (-1.0):+.1f}db".lower(),
        f"{measured_tp - (-1.0):.1f}db".lower(),
        f"{measured_corr:+.2f}".lower(),
        f"{measured_corr:.2f}".lower(),
        f"{measured_plr:.1f}db".lower(),
        f"{measured_low_mid * 100.0:.1f}%".lower(),
        f"{measured_sub * 100.0:.1f}%".lower(),
        f"{measured_air * 100.0:.1f}%".lower(),
    })

    for lever in levers:
        expl = lever["explanation"]
        full_text = (
            f"{expl['teaching_prose']} {expl['measurement_context']} "
            f"{expl['auditory_cues']['before']} {expl['auditory_cues']['after']}"
        )
        extracted = _extract_measurements_from_text(full_text)

        for m in extracted:
            # Drop integer vs decimal differences (e.g. 10khz vs 10.0khz)
            m_clean = re.sub(r"^(-?\d+)\.0([a-z%]+)$", r"\1\2", m)
            assert (
                m in allowed or m_clean in allowed
            ), f"Hallucinated or ungrounded measurement '{m}' in lever {lever['lever_id']}"


