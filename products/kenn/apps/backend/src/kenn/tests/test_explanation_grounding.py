def test_all_penalized_dimensions_generate_structured_pedagogical_explanations():
    """Verify that every penalized dimension produces structured teaching prose."""
    fake = FakeLiveBackend()
    snapshot = fake.query_session_state()

    penalized_meters = {
        "rms_dbfs": -14.0,
        "integrated_lufs": -11.0,
        "true_peak_dbtp": 0.40,  # clipping (+1.4 dB over -1.0 dBTP ceiling)
        "phase_correlation": -0.20,  # cancellation (< 0.0)
        "crest_factor_db": 4.5,  # hyper-compressed (< 6.0 dB)
        "spectral_energy": {
            "sub_20_60hz": 0.50,  # sub excess (> 45.0%)
            "low_mid_200_500hz": 0.45,  # mud (> 38.0%)
            "high_mid_2_6khz": 0.20,
            "air_10_20khz": 0.05,  # air deficit (< 10.0%)
        },
    }
    grade = _grade_for_meters(penalized_meters, snapshot)
    levers = generate_suggestion_levers(grade, snapshot, meters=penalized_meters)

    assert len(levers) >= 5, "Expected levers for all penalized dimensions"

    for lever in levers:
        expl = lever.get("explanation")
        assert expl is not None, f"Lever {lever['lever_id']} is missing an explanation"

        # Check required schema fields
        for field in ("metric_name", "measurement_context", "auditory_cues", "cited_standards", "teaching_prose"):
            assert field in expl, f"Explanation for {lever['lever_id']} missing {field}"

        # Auditory cues must provide specific before and after listening guidance
        cues = expl["auditory_cues"]
        assert isinstance(cues, dict)
        assert "before" in cues and "after" in cues
        assert len(cues["before"]) > 20, "Before cue must describe audible flaws"
        assert len(cues["after"]) > 20, "After cue must describe expected resolution"

        # Auditory verbs verify intentional listening guidance
        prose_lower = (cues["before"] + " " + cues["after"] + " " + expl["teaching_prose"]).lower()
        assert any(v in prose_lower for v in ("listen", "audition", "verify", "check", "toggle", "confirm"))

        # Standards citation check
        standards = expl["cited_standards"]
        assert len(standards) >= 1, f"Lever {lever['lever_id']} must cite at least one standard"


