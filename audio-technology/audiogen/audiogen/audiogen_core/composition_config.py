from __future__ import annotations

from dataclasses import dataclass, field
from typing import TYPE_CHECKING, List, Optional

from audiogen_core.arrangement_config import ArrangementConfiguration
from audiogen_core.composition_config_groups import CompositionRuntimeProfile, build_composition_runtime_profile

if TYPE_CHECKING:
    from audiogen_core.composition_config_groups import (
        HarmonyTensionControlGroup,
        MelodyPhrasePlanningGroup,
        MelodyRoleDensityGroup,
        RealtimeFormGroup,
    )


@dataclass
class CompositionConfiguration(ArrangementConfiguration):
    quantization_strength: float = 0.8
    quantization_grid: int = 16
    swing_enabled: bool = False
    swing_amount: float = 0.0
    humanization_enabled: bool = False
    humanization_amount: float = 0.02
    # Higher = more motif reuse across phrases (hook-forward).
    # Default is slightly lower so continuous playback doesn't "stuck hook" per emotion.
    motif_use_chance: float = 0.90
    motif_variation_increment: float = 0.15
    motif_max_variation: float = 0.8
    use_voice_leading: bool = True
    blend_enabled: bool = True
    blend_min: float = 0.3
    blend_max: float = 0.7
    default_tempo: float = 70.0
    bass_patterns: List[List[float]] = field(default_factory=lambda: [[0.0, 2.0], [0.0, 1.0, 2.0, 3.0]])
    chord_patterns: List[List[float]] = field(
        default_factory=lambda: [[0.0], [0.0, 2.0], [0.0, 1.0, 2.0, 3.0], [0.0, 1.5, 3.0]]
    )
    use_extensions: bool = True
    extension_prob: float = 0.3
    use_modal_interchange: bool = True
    interchange_prob: float = 0.2
    use_secondary_dominants: bool = True
    secondary_dominant_prob: float = 0.15
    embellishment_prob: float = 0.2
    # Lower = more literal restatements (strong hooks, less wandering).
    # Default is higher so phrases self-variation emerges even within one emotion.
    motif_variation_prob: float = 0.12
    pop_ext_force_hook_restatement: bool = True
    hook_restatement_enabled: bool = True
    enforce_melody_climax: bool = False
    # Lock section-level arp style per emotion (mode/register/feel), tuned from gold standards.
    arp_style_table_enabled: bool = True
    # Much looser default so the arp doesn't get stuck in one repetitive bed per emotion.
    arp_style_table_strength: float = 0.35
    # Optional: chorus-only arp fit from external WAV references
    # (generated by tools/analyze_reference_wavs.py + tools/suggest_tuning_from_metrics.py).
    chorus_reference_arp_enabled: bool = False
    chorus_reference_arp_path: str = ".cache/tuning_suggestions.json"
    chorus_reference_arp_strength: float = 0.85
    # Chorus references were rendered as section peaks; scale target notes slightly
    # when applying to runtime so chorus stays energized without affecting verses.
    chorus_reference_arp_target_boost: float = 1.25
    # Optional: chorus-only melody fit from external WAV references.
    chorus_reference_melody_enabled: bool = False
    chorus_reference_melody_path: str = ".cache/tuning_suggestions.json"
    chorus_reference_melody_strength: float = 0.70
    # Scale reference notes-per-bar before blending into melody density.
    chorus_reference_melody_target_boost: float = 1.10
    # Keep chord register stable across sections by anchoring a running "chord lane".
    chord_register_anchor_enabled: bool = True
    # Lower default so progressions + voicings can drift and feel less copy/paste.
    chord_register_anchor_strength: float = 0.60
    chord_register_anchor_chorus_lift: int = 2

    # ------------------------------------------------------------------
    # Register lanes (DAW-like “range targets” per part)
    # These are *targets* used by the section planner to keep parts in a
    # consistent, produced register (reduces octave “teleports”).
    # ------------------------------------------------------------------
    melody_lane_center_midi: int = 72
    melody_lane_half_width: int = 10
    chords_lane_offset_from_melody: int = 12
    chords_lane_half_width: int = 10
    arp_lane_offset_from_melody: int = 0
    arp_lane_half_width: int = 9

    # Tension trajectory (per-bar 0..1-ish) used to co-drive multiple layers.
    tension_trajectory_enabled: bool = True
    tension_trajectory_strength: float = 0.85

    # Timeline target shaping (section planner)
    timeline_tension_spike_center: float = 0.68
    timeline_tension_spike_width: float = 0.28
    timeline_tension_spike_power: float = 1.45

    # Instrument-aware velocity curves (post-pass on events).
    velocity_curves_enabled: bool = True
    velocity_curves_strength: float = 0.2
    # Add small per-note velocity jitter to polyphonic chord hits (MIDI velocity units).
    # Set to 0 to disable. Typical realistic range: 3–8.
    chord_note_velocity_jitter: int = 5
    # Small per-note velocity jitter for monophonic parts (MIDI velocity units).
    # Set to 0 to disable. Keep small to avoid perceived dynamics shifts.
    melody_velocity_jitter: int = 5
    arp_velocity_jitter: int = 5
    bass_density: float = 2.0
    bass_style: str = "simple"
    global_scale_intervals: Optional[List[int]] = None
    # ------------------------------------------------------------------
    # Key lock (preset-facing): force all emotions into a shared key center
    # ------------------------------------------------------------------
    key_lock_enabled: bool = False
    # Fixed tonic centers (MIDI note numbers) used when key lock is enabled.
    key_lock_major_root_midi: int = 60  # C4
    key_lock_minor_root_midi: int = 57  # A3
    # Scale interval sets (relative to root) used when key lock is enabled.
    key_lock_major_scale_intervals: List[int] = field(default_factory=lambda: [0, 2, 4, 5, 7, 9, 11])
    key_lock_minor_scale_intervals: List[int] = field(default_factory=lambda: [0, 2, 3, 5, 7, 8, 10])
    # ------------------------------------------------------------------
    # Per-song key variation: transpose each generated song to a fresh tonic
    # so successive generations of the same emotion aren't always in C.
    # Applied ONLY when key_lock is off (key_lock takes precedence). The whole
    # song derives from one root, so this is a coherent transposition (melody,
    # harmony and bass all move together). Offsets are semitones from the base
    # root (60); the pool is kept within a comfortable octave to preserve the
    # emotion's register and stay in sample range.
    # ------------------------------------------------------------------
    key_variation_enabled: bool = True
    key_variation_root_offsets: List[int] = field(default_factory=lambda: [-5, -3, -2, 0, 2, 4, 5, 7])
    # Avoid immediately repeating the previous song's key (more perceived variety).
    key_variation_avoid_immediate_repeat: bool = True
    # ------------------------------------------------------------------
    # Per-song tempo jitter: small +/- variation around the emotion's base tempo
    # so successive generations of the same emotion don't always land at the
    # exact same bpm. Applied as a multiplier on base_tempo_bpm, so it composes
    # cleanly with the existing emotion tempo_multiplier.
    # ------------------------------------------------------------------
    tempo_variation_enabled: bool = True
    tempo_variation_max_pct: float = 0.06  # +/- 6%
    # If true, quantize generated chord tones to the emotion scale (unless a global_scale is explicitly set).
    force_emotion_scale_quantization: bool = True
    # Derive a compatible scale from the emotion's chord pools (union of chord tone pitch classes),
    # so strict quantization doesn't neutralize intended harmony.
    derive_emotion_scale_from_chords: bool = True
    use_policy_phrase_contour_override: bool = True
    humanization_probability: float = 0.3
    # Stronger anti-repeat pressure so progressions evolve more.
    chord_repeat_penalty: float = 0.85
    max_chord_repeats: int = 1
    force_change_prob: float = 0.30
    drone_always_on: bool = False
    drone_fixed_midi: Optional[int] = None
    # Live playback: keep the drone continuous across emotion/root switches (no restart, no retune).
    # This does NOT force the drone to be enabled; it only prevents resetting its locked pitch/state.
    drone_keep_playing_on_switch: bool = True
    stable_emotion_dynamics: bool = True
    global_tempo_scale: float = 1.0
    # Global lead density scaler (lower = fewer melody notes overall).
    melody_amount_scale: float = 0.82
    neural_phrase_generator_enabled: bool = False
    # How strongly to enforce per-emotion melody behaviour profiles (0..1).
    # Higher values push density/register/rhythm closer to emotion-specific targets.
    emotion_melody_strictness: float = 0.7
    # Global multiplier on top of emotion-driven density (1.0 = neutral).
    emotion_melody_density_bias: float = 1.0
    # Global transpose offset applied to emotion-driven melody registers (in semitones).
    emotion_melody_register_bias_semitones: int = 0
    # Global multiplier on Markov rest probability (higher = more gaps).
    # Lower = fewer gaps in the lead so motifs read clearly.
    melody_rest_prob_mult: float = 0.88
    # Rest-insertion guardrail: keep at least this fraction of planned melody
    # notes per bar voiced, bounded by floor/ceiling below.
    melody_rest_min_voiced_bar_enabled: bool = True
    melody_rest_min_voiced_bar_ratio: float = 0.58
    melody_rest_min_voiced_bar_floor: int = 2
    melody_rest_min_voiced_bar_ceiling: int = 6
    # Repetition breaker threshold (higher = fewer replaced notes).
    melody_break_repeat_max: int = 6
    # Section-role melody density multipliers (Markov lead).
    # These are applied on top of emotion/profile/timeline shaping so section
    # roles read more distinctly (e.g. intro/outro sparser, chorus fuller).
    # Grouped read access: `melody_role_density` -> `core.composition_config_groups.MelodyRoleDensityGroup`.
    melody_role_density_intro_mult: float = 0.90
    melody_role_density_verse_mult: float = 0.98
    melody_role_density_prechorus_mult: float = 1.04
    melody_role_density_chorus_mult: float = 1.10
    melody_role_density_tag_mult: float = 1.06
    melody_role_density_aprime_mult: float = 1.02
    melody_role_density_outro_mult: float = 0.68
    # Soft role caps/floors for target notes-per-bar after role multiplier.
    # Keep intros/outros from over-singing; keep choruses from collapsing.
    melody_role_intro_target_npb_max: float = 4.2
    melody_role_intro_target_npb_min: float = 2.9
    melody_role_verse_target_npb_min: float = 3.8
    melody_role_prechorus_target_npb_min: float = 4.8
    melody_role_outro_target_npb_max: float = 3.8
    melody_role_chorus_target_npb_min: float = 5.6
    # If arp is active in chorus-like roles, scale melody total-note budget by this
    # to create a clearer "arp bed + slower lead answer" relationship.
    # Default near 1.0 so the lead can stay present alongside a busy arp; lower values
    # thin the melody when you want stronger call/response.
    chorus_melody_duck_with_arp: float = 1.0
    # When True, keep the legacy "answer after the arp bed" entrance delays (up to ~1 bar).
    # Default False: melody can enter with the arp instead of waiting for space.
    melody_arp_call_response_delay_enabled: bool = False
    # When True, pass arp-derived occupied intervals into melody Markov as soft "anti-collision"
    # weights (call/response). When False, melody + arp are allowed to freely overlap.
    melody_arp_occupied_masking_enabled: bool = False
    # Coexistence tuning: arp occupancy is passed into Markov as soft masking weights.
    # Scale <1.0 makes the lead less likely to duck/rhythm-shift away from the arp grid.
    melody_arp_occupied_weight_global_scale: float = 0.62
    # Extra attenuation applied only when arp-derived occupied masking is active.
    melody_arp_mask_strength_scale_when_arp_masking: float = 0.55
    # If the realized lead median sits at/below the arp median (same register), lift
    # the whole lead by one octave when there is headroom under the melody ceiling.
    melody_octave_lift_vs_arp_when_median_at_or_below_arp: bool = True
    melody_octave_lift_vs_arp_max_median_gap_semitones: int = 2
    melody_octave_lift_vs_arp_min_headroom_semitones: int = 2
    # After arp is finalized: nudge individual lead notes by ±12 when they overlap the arp
    # in time and are within `melody_arp_clash_max_semitones` (0 = unison only).
    melody_octave_resolve_arp_clash_enabled: bool = True
    melody_arp_clash_max_semitones: int = 0
    melody_arp_clash_octave_resolve_prefer_up: bool = True
    # Late planner/finalize nudges that pushed chorus leads off integer beats vs dense arps.
    melody_chorus_strong_beat_shift_vs_arp_enabled: bool = False
    melody_dense_arp_downbeat_nudge_enabled: bool = False

    # ------------------------------------------------------------------
    # Arpeggiator octave behavior (Ableton-like occasional +12 reach)
    # ------------------------------------------------------------------
    # If True, allow the arp bed to occasionally jump an octave up on weak steps.
    arp_octave_reach_enabled: bool = True
    # Global multiplier on the engine's computed octave reach probability.
    # (0 disables; 1 keeps emotion-derived defaults; >1 makes more octave jumps.)
    arp_octave_reach_strength: float = 1.0
    # On the last arp grid step of a bar, with this probability, nudge the pitch toward
    # the *next* bar's chord (anticipation color). Default 0 keeps arp notes within the
    # chord pool for the active harmonic-rhythm step (same-time with the progression).
    arp_next_bar_last_step_hint_prob: float = 0.0
    # Occasionally replace an arp step with a sustained tonic/fifth note (+octave),
    # lasting the full chord (bar) duration.
    arp_tonic_fifth_drone_note_enabled: bool = False
    arp_tonic_fifth_drone_note_prob: float = 0.0
    arp_tonic_fifth_drone_note_octave_semitones: int = 12
    # Pre-compute harmonic-rhythm Markov actions once per section (deterministic side-RNG) and
    # reuse them in both the arpeggiator and chord comping so arp chord-index steps match pads.
    arp_chord_harmonic_rhythm_shared_enabled: bool = True
    cadence_strength: float = 1.30
    melody_cadence_strength: float = 1.25
    # Harmony-function contracts: strengthen T/PD/D targets near phrase boundaries.
    harmony_function_contracts_enabled: bool = True
    harmony_function_contract_strength: float = 0.72  # 0..1
    use_rhythmic_chord_layers: bool = True
    chord_hits_decouple_from_changes: bool = True
    # Allow intra-bar harmonic changes (2 or 3 chord targets within a bar) when harmonic rhythm is high.
    chord_intra_bar_change_enabled: bool = True
    chord_intra_bar_change_strength: float = 0.25  # 0..1
    chord_intra_bar_change_max_splits: int = 3      # 1=off, 2=two-per-bar, 3=three-per-bar

    # ------------------------------------------------------------------
    # Realtime harmony tension control
    # ------------------------------------------------------------------
    # Grouped read access: `harmony_tension` -> `HarmonyTensionControlGroup` in
    # `core.composition_config_groups`.
    # Ties augmentation frequency (secondary dominants / modal interchange / chord
    # extensions — see chord_utils.py) to each section's tension level, which is
    # itself derived from the emotion's own tension-arc template
    # (data/tension_arc_dynamics.py). Was a documented but disabled (0.0) no-op;
    # enabled 2026-07-02 as part of tightening emotion accuracy in the harmony
    # augmentation layer — see docs/AUDIOGEN_COMPOSITION_PLAN.md item 9. Calm
    # moments get restrained harmonic color (low cap), tense moments keep full
    # baseline color (high cap stays at the historical no-op value of 1.0) —
    # this only ever *reduces* color relative to before, never adds beyond it,
    # so it's a safe first step to validate by ear before going further.
    # 0..1: master strength for tension-shaped harmony motion (color caps + HR bias).
    harmony_tension_control_strength: float = 0.7
    # 0..1: multiplicative cap applied to chord color probabilities at low tension.
    harmony_color_cap_low_tension: float = 0.5
    # 0..1: multiplicative cap applied to chord color probabilities at high tension.
    harmony_color_cap_high_tension: float = 1.0
    # 0..1: sensitivity of harmonic rhythm choices to per-bar tension.
    harmonic_rhythm_tension_sensitivity: float = 0.4
    # Section-role harmony pacing: verse/intro/outro hold more, pre-chorus moves
    # more, chorus stabilizes for hooks, bridge/a_prime can carry a surprise chord.
    harmony_pacing_policy_enabled: bool = True
    harmony_pacing_policy_strength: float = 1.0

    # ------------------------------------------------------------------
    # Markov style consistency (defaults are no-op)
    # ------------------------------------------------------------------
    # 0..1: master strength for style-profile reweighting across Markov layers.
    markov_style_strength: float = 0.45

    # Longform contrast scheduling (helps continuous playback avoid "samey" sections)
    contrast_every_n_sections: int = 2
    contrast_strength: float = 0.42  # 0..1

    # ------------------------------------------------------------------
    # Realtime form scheduling (non-arranged continuous playback)
    # ------------------------------------------------------------------
    # Grouped read access: `realtime_form` -> `RealtimeFormGroup` in `core.composition_config_groups`.
    # If enabled, the realtime player loops the form body (e.g. A→pre→B→A→B…)
    # instead of getting stuck in the terminal role of the form sequence.
    realtime_form_loop_enabled: bool = True
    # Optional: override which form sequence to loop (uses `ArrangementPolicy.form_mode` when empty).
    # Examples: "default", "pop", "pop_ext", "rondo", "ballad", "wave"
    realtime_form_mode_override: str = ""
    # If True, omit any terminal "outro" role from the loop body.
    realtime_form_loop_drop_outro: bool = True
    # When ``CompositionGenerator.runtime_generation_mode`` is not ``normal`` (live player ladder),
    # optionally cap expensive planning passes. ``full`` preserves legacy behavior.
    # ``light`` reduces best-of-K section picks and joint-generation iterations.
    # ``minimal`` forces the fastest section path and skips global voice-leading optimisation.
    realtime_planner_effort: str = "full"

    # ------------------------------------------------------------------
    # Realtime texture + form gestures
    # ------------------------------------------------------------------
    # 0..1: drop/thinning strength around breath/cadence/build moments.
    texture_drop_strength: float = 0.45
    # 0..1: amount of chorus/tag register lift applied in finalize shaping.
    texture_register_lift_strength: float = 0.55
    # 0..1: enable per-bar FX gestures (space/width/grit) driven by bar trace.
    texture_fx_gesture_strength: float = 0.32
    # Section-level energy arc length for realtime looping (used to compute rt_energy).
    realtime_energy_arc_length: int = 8

    # Arrangement energy matrix:
    # role-aware per-lane/per-target scaling (melody/chord/motif/tension + layer presence)
    # applied on top of timeline targets to make form contrast audibly stronger.
    arrangement_energy_matrix_enabled: bool = True
    arrangement_energy_matrix_strength: float = 0.72  # 0..1
    # Whole-song director:
    # applies a global intro->verse->pre->chorus->return->payoff energy arc on top
    # of local role curves so arranged renders read as full songs, not adjacent loops.
    whole_song_director_enabled: bool = True
    whole_song_director_strength: float = 0.68
    whole_song_final_chorus_lift: float = 0.14
    whole_song_chorus_hook_memory_enabled: bool = True
    whole_song_chorus_hook_memory_strength: float = 0.78

    # 16-bar A/B development intent: how much the second half should evolve
    # (more motion/motif, slightly higher density). Used by SectionPlanner timeline targets.
    ab_development_strength: float = 0.15  # 0..0.5

    # Cinematic chord comping patterns (deterministic vocabulary, not pure randomness).
    chord_comping_enabled: bool = True
    chord_comping_strength: float = 0.8  # 0..1 (how often to use vocab vs fallback heuristics)
    chord_comping_anticipation_prob: float = 0.06  # cinematic: rare

    # Phrase defaults (bars). Used across harmony/microtiming/voicing to keep
    # section structure coherent and configurable.
    phrase_length_bars: int = 4
    # Larger structural boundary (e.g. A/B split in 16-bar sections).
    superphrase_length_bars: int = 8

    # Live transition (emotion switch) shaping
    transition_enabled: bool = True
    # Minimum shared pitch classes for bar-0 chord pivot selection.
    transition_common_tone_min: int = 1
    # If True, avoid motif-first openings on the first phrase after a handoff.
    transition_disable_motif_first: bool = True
    # After a manual emotion switch, blend the first N bars of per-bar generation targets
    # (melody density / chord rhythm / tension / motif strength) from the previous emotion
    # into the new emotion to avoid an abrupt musical jump. 0 disables blending.
    transition_blend_bars: int = 4
    # Optional “bridge” window right after a manual emotion switch.
    # - transition_bridge_bars: conceptual bridge length (used by planners as a cap / tuning hint).
    # - transition_bridge_hold_bars: number of initial bars that should hold strong continuity
    #   anchors from the outgoing section (previous bass note, high common-tone chord pivot).
    transition_bridge_bars: int = 4
    transition_bridge_hold_bars: int = 2
    # Stronger phrase-aware handoff shaping near section endings.
    transition_composer_phrase_handoff_enabled: bool = True
    transition_composer_phrase_handoff_strength: float = 0.82
    # Slow harmonic center drift across sections (keeps long playback evolving
    # while still returning toward tonal home near the form end).
    tonal_center_drift_enabled: bool = True
    tonal_center_drift_strength: float = 0.55
    tonal_center_drift_max_semitones: int = 3
    tonal_center_drift_cycle_sections: int = 8
    melody_target_notes_per_bar: float = 6.0
    melody_register_arc_enabled: bool = True
    seed: Optional[int] = None
    # True when the user explicitly passes `--seed` (repeatable runs). Used to decide
    # whether realtime-only previews may inject extra randomness beyond the base seed.
    user_pinned_seed: bool = False
    deterministic_seeded_offline_renders: bool = True
    # If True, clicking/selecting an emotion in generative mode reseeds + resets song memory
    # so you get a fresh variation instead of replaying the same deterministic generation.
    reseed_on_emotion_change_enabled: bool = True
    chord_k_samples: int = 3
    chord_rerank_change_bonus: float = 0.10
    chord_rerank_cadence_bonus: float = 0.14
    # Slightly hotter chord sampling = more different progressions per run.
    chord_temp_opening_mult: float = 1.10
    chord_temp_continuation_mult: float = 1.12
    chord_temp_answer_mult: float = 1.06
    chord_temp_cadence_mult: float = 0.98
    # Grouped read access (phrase beam / rerank / scorers): `melody_phrase_planning`.
    melody_k_samples: int = 4
    # Phrase-level best-of-K (select the most "composed" phrase among K samples).
    # Phrase-level best-of-K: higher yields more "composed" motifs at some CPU cost.
    melody_phrase_k_samples: int = 3
    # Phrase beam rerank: wider candidate frontier + shortlist rerank.
    melody_phrase_beam_enabled: bool = True
    melody_phrase_beam_width: int = 7
    melody_phrase_beam_keep: int = 3
    melody_phrase_beam_diversity_weight: float = 0.12
    melody_phrase_beam_lookahead_weight: float = 0.18
    # Phrase rerank memory model: balance immediate novelty with structural recall.
    melody_listener_memory_scorer_enabled: bool = True
    melody_listener_memory_scorer_strength: float = 0.68
    # Lyrical-minimalist beauty scorer: rewards stepwise motion, recoveries after
    # leaps, small recurring motifs, breath, stable cadences, and focused range.
    lyrical_melody_scorer_enabled: bool = True
    lyrical_melody_scorer_strength: float = 0.48
    melody_phrase_rerank_entry_leap_penalty: float = 0.26
    melody_phrase_rerank_large_leap_penalty: float = 0.06
    melody_phrase_rerank_large_leap_threshold: int = 4
    melody_phrase_rerank_cadence_land_bonus: float = 0.55
    melody_phrase_rerank_cadence_approach_bonus: float = 0.24
    melody_phrase_rerank_cadence_miss_penalty: float = 0.22
    melody_rerank_opening_stepwise_bonus: float = 0.08
    melody_rerank_opening_chord_tone_bonus: float = 0.07
    melody_rerank_cadence_target_bonus: float = 0.18
    melody_rerank_cadence_approach_bonus: float = 0.05
    melody_rerank_mid_contour_bonus: float = 0.04
    melody_rerank_motif_continue_bonus: float = 0.05
    # Short-horizon lookahead for rerank (phrase openings/cadences).
    melody_rerank_lookahead_weight: float = 0.22
    melody_rerank_lookahead_top_m: int = 7
    # 0..1: promotes ai/markov/melody/beauty.py's "leap recovery" scoring signal (does a
    # leap get followed by a step back — the classic melody-writing rule) from a post-hoc
    # rerank-only nudge into an active generation-time bias. Added 2026-07-02, see
    # docs/AUDIOGEN_COMPOSITION_PLAN.md item 14. 0 = no bias (old behavior, rely on rerank
    # alone); higher values more strongly favor a stepwise interval immediately after a
    # wrapped-distance-3+ leap.
    melody_leap_recovery_bias_strength: float = 0.35
    # <1.0 in chorus(-like) roles: slightly more leaps / color vs chord-on-every-beat blandness.
    melody_role_chorus_stepwise_mult: float = 0.90
    melody_role_chorus_chord_tone_mult: float = 0.94
    melody_role_verse_leap_mult: float = 1.0
    melody_role_outro_stepwise_mult: float = 1.0
    # Joint fit: on strong beats, bias interval selection toward chord tones (degree-space).
    # 1.0 = neutral; >1.0 improves chord-tone fit (can reduce melodic "spice" if too high).
    melody_strongbeat_chord_tone_mult: float = 3.25
    # Strong-beat chord-tone contract:
    # when enabled, notes that start on strong beats and are "long enough" are
    # heavily discouraged from landing on non-chord tones (phrase-level logic also helps,
    # but this is a per-note guardrail).
    melody_strongbeat_chordtone_contract_enabled: bool = True
