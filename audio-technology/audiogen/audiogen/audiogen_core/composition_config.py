def apply_melody_staged_experimental_bundle(comp: CompositionConfiguration) -> None:
    """Turn on staged Markov melody experiments (coupling, joint rerank, breath)."""
    if not getattr(comp, "melody_staged_experimental_bundle_enabled", False):
        return
    comp.melody_rhythm_pitch_coupling_enabled = True
    comp.melody_interval_duration_coupling_enabled = True
    comp.melody_joint_rhythm_pitch_rerank_enabled = True
    if int(getattr(comp, "melody_joint_rhythm_pitch_rerank_k", 0) or 0) <= 0:
        comp.melody_joint_rhythm_pitch_rerank_k = 8
    comp.melody_breath_rest_bias_enabled = True
    comp.melody_breath_rhythm_bias_enabled = True
