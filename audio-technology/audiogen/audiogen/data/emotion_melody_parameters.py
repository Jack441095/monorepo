def _apply_overrides(base_params, overrides):
    tuned = {name: dict(params) for name, params in base_params.items()}
    for emotion_name, override in overrides.items():
        if emotion_name not in tuned:
            continue
        tuned[emotion_name].update(override)
    return tuned


