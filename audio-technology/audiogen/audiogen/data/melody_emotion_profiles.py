def melody_emotion_profile_for_emotion(emotion_name: str) -> MelodyEmotionProfile:
    """
    Return the MelodyEmotionProfile for an emotion name.

    Unknown names fall back to a neutral profile.
    """
    key = canonical_emotion_name(emotion_name or "")
    prof = _PROFILES.get(key)
    if prof is not None:
        return prof
    return _PROFILES["neutral"]
