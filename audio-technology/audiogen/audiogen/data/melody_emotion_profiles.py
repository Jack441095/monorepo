from __future__ import annotations

from dataclasses import dataclass
from typing import Dict

from data.emotion_aliases import canonical_emotion_name


@dataclass(frozen=True)
class MelodyEmotionProfile:
    """
    High-level, emotion-specific melody controls.

    These are lightweight scalar knobs that sit on top of EmotionProfile and the
    existing rhythm / articulation profiles. They are intentionally simple so
    they can be tuned by ear and inspected easily.
    """

    name: str

    # Rough affect coordinates (for future use / tuning helpers).
    # valence: -1 = very negative, +1 = very positive.
    # arousal: 0 = very calm, 1 = very intense.
    valence: float
    arousal: float

    # Density / note-count shaping for the lead melody.
    # 1.0 = neutral; >1 = denser; <1 = sparser (before global melody_amount_scale).
    density_mult: float = 1.0
    # Optional per-emotion floor for notes per bar (in addition to data-driven min).
    min_notes_per_bar: float = 1.0

    # Phrase contour tendencies. Values are relative weights; 1.0 = neutral.
    contour_static_bias: float = 1.0
    contour_asc_bias: float = 1.0
    contour_desc_bias: float = 1.0
    contour_arch_bias: float = 1.0

    # Register behaviour for the lead melody.
    # Base semitone shift applied before range limiting (e.g. +12 = an octave up).
    register_shift_semitones: int = 0
    # Approximate desired span (for future use in phrase-planning / scoring).
    register_span_semitones: int = 12
    # Chance per phrase to introduce an octave jump for extra drama.
    octave_jump_chance: float = 0.0

    # Rhythm feel refinements on top of EMOTION_MELODY_RHYTHM_PROFILES.
    # 1.0 = neutral; >1 = more syncopation/short notes/long notes respectively.
    syncopation_bias: float = 1.0
    short_note_bias: float = 1.0
    long_note_bias: float = 1.0

    # How strongly phrases should close (cadential pull) vs. stay open.
    # 1.0 = neutral; >1 = more decisive closure; <1 = more open/unfinished.
    cadence_closure_strength: float = 1.0


