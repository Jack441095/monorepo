def get_interval_bias(contour: str, position_in_phrase: float) -> Dict[int, float]:
    """
    Return a dictionary mapping intervals to bias factors based on contour and position.
    """
    if contour == 'asc':
        return {1: 2.0, 2: 1.5, 3: 1.2, 0: 0.5, -1: 0.3, -2: 0.2}
    elif contour == 'desc':
        return {-1: 2.0, -2: 1.5, -3: 1.2, 0: 0.5, 1: 0.3, 2: 0.2}
    elif contour == 'arch':
        if position_in_phrase < 0.5:
            return {1: 2.0, 2: 1.5, 0: 0.6, -1: 0.4}
        else:
            return {-1: 2.0, -2: 1.5, 0: 0.6, 1: 0.4}
    elif contour == 'static':
        return {0: 3.0, 1: 0.8, -1: 0.8, 2: 0.3, -2: 0.3}
    else:
        return {}
